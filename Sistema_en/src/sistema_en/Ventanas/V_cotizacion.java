    private void b_guardar_pdfActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_b_guardar_pdfActionPerformed
        // 1. Validar que la tabla tenga datos
        bloquear_botones();
    if (Tabla_conceptos.getRowCount() == 0) {
        javax.swing.JOptionPane.showMessageDialog(this, "La tabla de conceptos está vacía.", "Aviso", javax.swing.JOptionPane.WARNING_MESSAGE);
        desbloquear_botones();
        return;
    }

    // 2. Seleccionar dónde guardar el archivo .txt
    javax.swing.JFileChooser selectorDestino = new javax.swing.JFileChooser();
    selectorDestino.setDialogTitle("Guardar Cotización como Texto");
    String trabajoId = t_numero_trabajo.getText().trim();
    String nombreSugerido = "Cotizacion_" + (trabajoId.isEmpty() ? "Nueva" : trabajoId) + ".txt";
    selectorDestino.setSelectedFile(new java.io.File(nombreSugerido));

    if (selectorDestino.showSaveDialog(this) == javax.swing.JFileChooser.APPROVE_OPTION) {
        java.io.File archivoTxt = selectorDestino.getSelectedFile();

        // 3. Usar try-with-resources para escribir el archivo de texto de forma segura
        try (java.io.FileWriter fw = new java.io.FileWriter(archivoTxt);
             java.io.PrintWriter pw = new java.io.PrintWriter(fw)) {

            // Encabezado del ticket / cotización
            pw.println("==================================================");
            pw.println("     ██████████      ███        ███");
            pw.println("     ███             ████       ███");
            pw.println("     ███             █████      ███");
            pw.println("     █████████       ███ ██     ███");
            pw.println("     ███             ███  ██    ███");
            pw.println("     ███             ███   ██   ███");
            pw.println("     ██████████      ███    ███████");
            pw.println("                 ESTIBEN NAVARRO                  ");
            pw.println("           SOLUCIONES HIDRO-SANITARIAS            ");
            pw.println("==================================================");
            pw.println();
            
            // Datos generales
            pw.println("Número de Trabajo:    " + t_numero_trabajo.getText());
            pw.println("Número de Cotización: " + t_numero_cotizacion.getText());
            pw.println("Fecha de Emisión:     " + new java.text.SimpleDateFormat("dd/MM/yyyy HH:mm").format(new java.util.Date()));
            pw.println();
            pw.println("--------------------------------------------------");
            
            // Encabezados de la tabla con formato alineado
            // %-35s significa: texto alineado a la izquierda ocupando 35 espacios
            // %12s significa: texto alineado a la derecha ocupando 12 espacios
            pw.printf("%-35s %12s%n", "CONCEPTO", "PRECIO");
            pw.println("--------------------------------------------------");

            // 4. Recorrer las filas del JTable e imprimirlas en el TXT con ajuste de palabra inteligente
            int totalFilas = Tabla_conceptos.getRowCount();
            for (int i = 0; i < totalFilas; i++) {
                String concepto = Tabla_conceptos.getValueAt(i, 0) != null ? Tabla_conceptos.getValueAt(i, 0).toString() : "";
                String precioStr = Tabla_conceptos.getValueAt(i, 1) != null ? Tabla_conceptos.getValueAt(i, 1).toString() : "0.0";
                
                double precio = 0.0;
                try {
                    precio = Double.parseDouble(precioStr);
                } catch (NumberFormatException e) {
                    // En caso de error, se mantiene en 0.0
                }

                java.util.List<String> lineasConcepto = wrapText(concepto, 33);
                if (lineasConcepto.isEmpty()) {
                    lineasConcepto.add("");
                }
                
                // Imprimir líneas previas (sin precio)
                for (int j = 0; j < lineasConcepto.size() - 1; j++) {
                    pw.println(lineasConcepto.get(j));
                }
                // Imprimir la última línea junto con el precio alineado y formateado
                String ultimaLinea = lineasConcepto.get(lineasConcepto.size() - 1);
                pw.printf("%-35s $%,11.2f%n", ultimaLinea, precio);
            }

            // 5. Total final
            pw.println("--------------------------------------------------");
            double subtotal = 0.0;
            try {
                subtotal = Double.parseDouble(t_subtotal.getText().isEmpty() ? "0.0" : t_subtotal.getText());
            } catch (NumberFormatException e) {
                // Manejo por si el subtotal de la interfaz está vacío o mal formateado
            }
            double iva = subtotal * 0.16;
            double totalConIva = subtotal + iva;
            
            pw.printf("%-35s $%,11.2f%n", "SUBTOTAL:", subtotal);
            pw.printf("%-35s $%,11.2f%n", "IVA (16%):", iva);
            pw.printf("%-35s $%,11.2f%n", "TOTAL A PAGAR:", totalConIva);
            pw.println("==================================================");
            pw.println();
            pw.println("         ¡Gracias por su confianza!               ");

            // Mensaje de éxito
            javax.swing.JOptionPane.showMessageDialog(this, "¡Cotización guardada exitosamente en formato TXT!", "Éxito", javax.swing.JOptionPane.INFORMATION_MESSAGE);

        } catch (java.io.IOException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error al escribir el archivo de texto: " + e.getMessage(), "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
            e.printStackTrace();
        }
    }
    
    desbloquear_botones();
    }//GEN-LAST:event_b_guardar_pdfActionPerformed

