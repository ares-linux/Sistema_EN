    private void b_editarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_b_editarActionPerformed
        
        if (Tabla_conceptos.getRowCount() == 0) {
        javax.swing.JOptionPane.showMessageDialog(this, "La tabla de conceptos está vacía.", "Aviso", javax.swing.JOptionPane.WARNING_MESSAGE);
        desbloquear_botones();
        return;
    }
        
        fila = Tabla_conceptos.getSelectedRow();
        if (b_editar.getText()=="Editar")
        {
            b_editar.setText("Guardar");
            b_eliminar.setEnabled(false);
            b_materiales.setEnabled(false);
            b_guardar.setEnabled(false);
            b_guardar_pdf.setEnabled(false);
            b_añadir.setEnabled(false);
            cargar_datos_tabla(fila);
        }
        else
        {
            if(t_concepto.getText().trim().isEmpty() || t_precio.getText().trim().isEmpty())
            {
                return;
            }
            
            b_editar.setText("Editar");
            editar_tabla();
            total();
            b_eliminar.setEnabled(true);
            b_materiales.setEnabled(true);
            b_guardar.setEnabled(true);
            b_guardar_pdf.setEnabled(true);
            b_añadir.setEnabled(true);
            limpiar_text();
        }
    }//GEN-LAST:event_b_editarActionPerformed

