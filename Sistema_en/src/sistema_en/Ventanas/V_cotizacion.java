    public void llenar_tabla(){
         String [] info =new String[2];//craeun arreglo tipo string de 7 elementos 
         //llena el arreglo con la informacion de mi objeto
         info[0]=this.t_concepto.getText();
         
         info[1]=this.t_precio.getText();
         
    
      DefaultTableModel modelo=(DefaultTableModel) this.Tabla_conceptos.getModel();//crea una variable de tipo modelo de tabla 
      modelo.addRow(info);//agrega una fila al modelo de tabla
      this.Tabla_conceptos.setModel(modelo);//actualiza el modelo de la tabla por el que posee la fila agregada
      } 
    
    public void editar_tabla(){
        DefaultTableModel modelo =(DefaultTableModel) this.Tabla_conceptos.getModel();
        modelo.setValueAt(this.t_concepto.getText(), fila, 0);
        modelo.setValueAt(this.t_precio.getText(), fila, 1);
        this.Tabla_conceptos.setModel(modelo); 
    }
    
    public void total(){
        double totalSuma = 0.0;

// Recorremos cada una de las filas de la tabla
for (int i = 0; i < Tabla_conceptos.getRowCount(); i++) {
    
    // Obtenemos el valor de la celda (Fila i, Columna 3)
    // NOTA: Recuerda que las columnas empiezan a contarse desde 0. 
    // Si tu columna es la cuarta, su índice es 3.
    Object valorCelda = Tabla_conceptos.getValueAt(i, 1);
    
    // Validamos que la celda no esté vacía para evitar errores (NullPointerException)
    if (valorCelda != null) {
        try {
            // Convertimos el valor a String y luego a Double para sumarlo
            double valorDecimal = Double.parseDouble(valorCelda.toString());
            totalSuma += valorDecimal;
        } catch (NumberFormatException e) {
            // Si la celda contiene texto no numérico por error, se salta la fila
            System.out.println("Error de formato en la fila " + i + ": No es un número válido.");
        }
    }
}

// Finalmente, mostramos el resultado en los campos correspondientes
double subtotal = totalSuma;
double iva = subtotal * 0.16;
double totalConIva = subtotal + iva;

t_subtotal.setText(String.format(java.util.Locale.US, "%.2f", subtotal));
t_iva.setText(String.format(java.util.Locale.US, "%.2f", iva));
t_total.setText(String.format(java.util.Locale.US, "%.2f", totalConIva));
    }
    
