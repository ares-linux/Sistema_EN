    public void cargar_Datos_Ficha(String id, String fecha, String hora, String estado, String cliente, String descripcion, String direccion) {
    // 1. Asignar los datos individuales a sus campos correctos
    t_id.setText(id);
    t_fecha.setText(fecha);   // Antes tenías aquí el estado cambiado
    t_hora.setText(hora);     // Antes tenías aquí la fecha cambiada
    t_estado.setText(estado); // Antes tenías aquí el cliente cambiado
    
    // 2. Limpiar y configurar el JList para la información del trabajo
    javax.swing.DefaultListModel<String> modeloLista = new javax.swing.DefaultListModel<>();
    
    modeloLista.addElement("CLIENTE:");
    modeloLista.addElement(" -> " + cliente);
    modeloLista.addElement("--------------------------------------");
    modeloLista.addElement("DESCRIPCIÓN DEL REPORTE:");
    modeloLista.addElement(descripcion);
    modeloLista.addElement("--------------------------------------");
    modeloLista.addElement( "Direccion del trabajo:"+ direccion);
    
    l_informacion_trabajo.setModel(modeloLista);
}
    
