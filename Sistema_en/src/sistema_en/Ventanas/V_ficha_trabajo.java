    private void b_actualizar_estadoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_b_actualizar_estadoActionPerformed
        if("Actualizar estado".equals(b_actualizar_estado.getText()))
        {
            c_estado.setEnabled(true);
            b_actualizar_estado.setText("Guardar");
            
        }
        else
        {
            b_actualizar_estado.setText("Actualizar estado");
            c_estado.setEnabled(false);
            registrar_pago();
        }
        
    }//GEN-LAST:event_b_actualizar_estadoActionPerformed

