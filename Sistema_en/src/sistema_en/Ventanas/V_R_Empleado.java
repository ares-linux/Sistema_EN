    public boolean verificar_edad() {
        java.time.LocalDate fechaNac = d_f_nac.getDate();
        if (fechaNac == null) {
            return false;
        }
    
        int edad = java.time.Period.between(fechaNac, java.time.LocalDate.now()).getYears();
    
        return edad >= 18;
               
    }
    
