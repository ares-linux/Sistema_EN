    public class r_sonido {

        public static void reproducir(String ruta) {
            try {
                File archivo = new File(ruta);
                AudioInputStream audio = AudioSystem.getAudioInputStream(archivo);

                Clip clip = AudioSystem.getClip();
                clip.open(audio);
                clip.start();

            } catch (Exception e) {
                e.printStackTrace();
            }
        }
    }
    
