    private void b_convertirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_b_convertirActionPerformed
        String nombre = t_nombre.getText().trim();
        String telefono = t_telefono.getText().trim();
        String direccion = t_direccion.getText().trim();
        String descripcion = T_descripcion.getText().trim();

        if (nombre.isEmpty() || telefono.isEmpty() || direccion.isEmpty() || descripcion.isEmpty()) {
            JOptionPane.showMessageDialog(this,
                    "Nombre, telefono, direccion y descripcion son obligatorios.",
                    "Aviso", JOptionPane.WARNING_MESSAGE);
            return;
        }

        // Evita crear un cliente duplicado sin avisar: se avisa y el usuario decide.
        if (new ConversionCotizacionDAO().clienteExiste(nombre, telefono)) {
            int opcion = JOptionPane.showConfirmDialog(this,
                    "Ya existe un cliente registrado con ese nombre y telefono.\n"
                    + "Si continua, el trabajo se asignara a ese mismo cliente.",
                    "Cliente ya registrado", JOptionPane.YES_NO_OPTION, JOptionPane.QUESTION_MESSAGE);
            if (opcion != JOptionPane.YES_OPTION) {
                return;
            }
        }

        final String estadoCotizacion = (String) c_estado.getSelectedItem();
        final String fecha = LocalDate.now().toString();
        final String hora = LocalTime.now().withNano(0).toString();

        setCamposHabilitados(false);
        setCursor(Cursor.getPredefinedCursor(Cursor.WAIT_CURSOR));

        new SwingWorker<Integer, Void>() {
            @Override
            protected Integer doInBackground() {
                int idTrabajo = new ConversionCotizacionDAO().convertirCotizacionEnTrabajo(
                        idCotizacion, nombre, telefono, direccion, descripcion,
                        fecha, hora, estadoCotizacion);
                if (idTrabajo != -1) {
                    prepararCarpetaDrive(idTrabajo, fecha);
                }
                return idTrabajo;
            }

            @Override
            protected void done() {
                setCursor(Cursor.getDefaultCursor());
                setCamposHabilitados(true);
                try {
                    int idTrabajo = get();
                    if (idTrabajo != -1) {
                        idTrabajoCreado = idTrabajo;
                        JOptionPane.showMessageDialog(D_convertir_trabajo.this,
                                "La cotizacion se covertio al trabajo " + idTrabajo + ".",
                                "Conversion realizada", JOptionPane.INFORMATION_MESSAGE);
                        D_convertir_trabajo.this.dispose();
                    } else {
                        JOptionPane.showMessageDialog(D_convertir_trabajo.this,
                                "No se pudo convertir la cotizacion. Revisa los datos e intenta de nuevo.",
                                "Error", JOptionPane.ERROR_MESSAGE);
                    }
                } catch (java.util.concurrent.ExecutionException | InterruptedException ex) {
                    JOptionPane.showMessageDialog(D_convertir_trabajo.this,
                            "Ocurrio un error inesperado al convertir: " + ex.getMessage(),
                            "Error", JOptionPane.ERROR_MESSAGE);
                }
            }
        }.execute();
    }//GEN-LAST:event_b_convertirActionPerformed

