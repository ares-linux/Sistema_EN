    /**
     * Crea la carpeta del trabajo en Drive. Solo se intenta si hay cuenta conectada,
     * para no abrir el navegador de autorizacion a mitad de una conversion. Si no hay
     * carpeta, el trabajo queda en "Pendiente" y sincronizarTrabajosPendientes() la
     * crea mas tarde, que es el mismo criterio que usa el alta de trabajos.
     */
    private void prepararCarpetaDrive(int idTrabajo, String fecha) {
        TrabajoDAO trabajoDao = new TrabajoDAO();
        Trabajo trabajo = trabajoDao.obtenerTrabajo(idTrabajo);
        if (trabajo == null) {
            return;
        }

        if (!GoogleServicesProvider.estaConectado()) {
            trabajoDao.actualizarTrabajoCarpeta(idTrabajo, "Pendiente");
            return;
        }

        String nombreCarpeta = "Trabajo_" + idTrabajo + "_" + trabajo.getId_cliente() + "_" + fecha;
        String idCarpetaDrive = GoogleServicesProvider.crearCarpetaTrabajo(nombreCarpeta);
        trabajoDao.actualizarTrabajoIdCarpeta(idTrabajo, idCarpetaDrive);
        trabajoDao.actualizarTrabajoCarpeta(idTrabajo, idCarpetaDrive != null ? "Creada" : "Pendiente");
    }

