    private void b_cerrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_b_cerrarActionPerformed
        if(b_actualizar_datos.isSelected() == true){
            int respuesta = javax.swing.JOptionPane.showConfirmDialog(this, "¿Desea cerrar sin guardar?", "Confirmacion", javax.swing.JOptionPane.YES_NO_OPTION, javax.swing.JOptionPane.QUESTION_MESSAGE);
            if (respuesta == javax.swing.JOptionPane.YES_OPTION){
                //b_actualizar_datos.setSelected(false);
                b_actualizar_datos.doClick();
                this.dispose();
            }
        }
        else{
            this.dispose();
        }
    }//GEN-LAST:event_b_cerrarActionPerformed

    private void b_actualizar_datosActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_b_actualizar_datosActionPerformed
        if(b_actualizar_datos.isSelected() == true){
            desbloquear_text();
            //b_foto.setEnabled(true);
        }
        else{
            bloquear_text();
            //b_foto.setEnabled(false);
        }
    }//GEN-LAST:event_b_actualizar_datosActionPerformed

