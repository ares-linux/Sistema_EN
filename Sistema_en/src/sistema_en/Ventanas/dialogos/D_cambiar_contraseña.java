    private void b_aceptar_cActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_b_aceptar_cActionPerformed
        String actual = new String(t_contraseña_a.getPassword());
        String nueva = new String(t_contraseña_n.getPassword());
        String confirmacion = new String(t_contraseña_c.getPassword());

        if (actual.isEmpty() || nueva.isEmpty() || confirmacion.isEmpty()) {
            aviso_labels();
            //javax.swing.JOptionPane.showMessageDialog(this, "Por favor, llena todos los campos.", "Campos vacíos", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }
    
        if (nueva.length() < 4 || nueva.trim().length() < 4){
            aviso_labels();
            //javax.swing.JOptionPane.showMessageDialog(this, "La nueva contraseña debe tener al menos 4 caracteres.", "Contraseña no válida", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }

        if (!nueva.equals(confirmacion)) {
            l_contraseña_c.setForeground(Color.decode("#CE1126"));
            javax.swing.JOptionPane.showMessageDialog(this, "La nueva contraseña y la confirmación no coinciden.", "Error de coincidencia", javax.swing.JOptionPane.ERROR_MESSAGE);
            return;
        } else {
            l_contraseña_c.setForeground(null);
        }
    
        int id = 1; 
        UsuariosDAO dao = new UsuariosDAO();

        String hashActualBD = dao.obtenerHashPorId(id);
    
        if (hashActualBD == null) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error al recuperar la información del usuario.", "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
            return;
        }
    
        if (!org.mindrot.jbcrypt.BCrypt.checkpw(actual, hashActualBD)) {
            l_contraseña_a.setForeground(Color.decode("#CE1126"));
            javax.swing.JOptionPane.showMessageDialog(this, "La contraseña actual es incorrecta.", "Acceso denegado", javax.swing.JOptionPane.ERROR_MESSAGE);
            return;
        } else {
            l_contraseña_a.setForeground(null);
        }
 
        boolean actualizadoExitoso = dao.actualizarContraseña(id, nueva); 
    
        if (actualizadoExitoso) {
            limpiar_text();
            javax.swing.JOptionPane.showMessageDialog(this, "¡Contraseña cambiada exitosamente!", "Éxito", javax.swing.JOptionPane.INFORMATION_MESSAGE);
            this.dispose();
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "No se pudo actualizar la contraseña.", "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_b_aceptar_cActionPerformed

