    public void aviso_labels(){
        
        boolean error = false;
        
        if (t_contraseña_a.getPassword().length == 0) {
            l_contraseña_a.setForeground(Color.decode("#CE1126"));
            error = true;
        }
        
        
        if (t_contraseña_a.getPassword().length != 0) {
            l_contraseña_a.setForeground(null);
            error = false;
        }
        
        if (t_contraseña_n.getPassword().length == 0) {
            l_contraseña_n.setForeground(Color.decode("#CE1126"));
            error = true;
        }
        
        
        if (t_contraseña_n.getPassword().length != 0) {
            l_contraseña_n.setForeground(null);
            error = false;
        }
        
        if (t_contraseña_c.getPassword().length == 0) {
            l_contraseña_c.setForeground(Color.decode("#CE1126"));
            error = true;
        }
        
        
        if (t_contraseña_c.getPassword().length != 0) {
            l_contraseña_c.setForeground(null);
            error = false;
        }
        
        String nueva = new String(t_contraseña_n.getPassword());

        if (nueva.length() < 4) {
            l_recordatorio.setForeground(Color.decode("#CE1126"));
            error = true;
        }
        else{
            l_recordatorio.setForeground(null);
            error = false;
        }
        
        if (nueva.trim().length() < 4) {
            l_recordatorio.setForeground(Color.decode("#CE1126"));
            error = true;
        }
        else{
            l_recordatorio.setForeground(null);
            error = false;
        }
        
    }
    
