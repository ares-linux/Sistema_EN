    private void cargarPeriodos() {
        dao.InformesDAO dao = new dao.InformesDAO();
        java.util.List<String> periodos = dao.obtenerPeriodosDisponibles();
        jComboBox1.removeAllItems();
        jComboBox2.removeAllItems();
        for (String p : periodos) {
            jComboBox1.addItem(p);
            jComboBox2.addItem(p);
        }
        if (periodos.size() > 1) {
            jComboBox1.setSelectedIndex(0);
            jComboBox2.setSelectedIndex(1);
        }
    }
    
    private void contrastarDatos() {
        if (jComboBox1.getSelectedItem() == null || jComboBox2.getSelectedItem() == null) {
            javax.swing.JOptionPane.showMessageDialog(this, "Seleccione ambos periodos.", "Aviso", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }
        String p1 = (String) jComboBox1.getSelectedItem(); // Informe actual
        String p2 = (String) jComboBox2.getSelectedItem(); // Comparar con
        
        if (p1.equals(p2)) {
            javax.swing.JOptionPane.showMessageDialog(this, "Los periodos deben ser distintos.", "Aviso", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }

        boolean numerico = jRadioButton1.isSelected();
        boolean textual = jRadioButton2.isSelected();
        boolean mixto = jRadioButton3.isSelected();
        
        if (!numerico && !textual && !mixto) {
            javax.swing.JOptionPane.showMessageDialog(this, "Seleccione el tipo de contraste.", "Aviso", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }

        D_resultados_contraste dialog = new D_resultados_contraste(this, true, p1, p2, numerico, textual, mixto);
        dialog.setLocationRelativeTo(this);
        dialog.setVisible(true);
    }

