    public void llenar_tabla(){
        
        DefaultTableModel modelo = (DefaultTableModel) this.Tabla_bitacoras.getModel();
        modelo.setRowCount(0); 
        
        BitacoraDAO dao = new BitacoraDAO();
        java.util.List<Bitacora> lista = dao.obtenerBitacoras(id_trabajo);
        
        for (Bitacora b : lista) {
            Object[] fila = {
            b.getId_trabajador(),
            b.getFecha(),
            b.getHora_llegada(),
            b.getHora_salida(),
            b.getEvidencias(),
            b.getNotas()
            };
            modelo.addRow(fila);
        }
        
    }
    
    public void filtrar_tabla(){
        String fecha_buscar = d_fecha.getDateStringOrSuppliedString("");
        
        DefaultTableModel modelo = (DefaultTableModel) this.Tabla_bitacoras.getModel();
        modelo.setRowCount(0); 
        
        BitacoraDAO dao = new BitacoraDAO();
        java.util.List<Bitacora> lista = dao.buscarBitacoras(id_trabajo, fecha_buscar);
        
        for (Bitacora b : lista) {
            Object[] fila = {
            b.getId_trabajador(),
            b.getFecha(),
            b.getHora_llegada(),
            b.getHora_salida(),
            b.getEvidencias(),
            b.getNotas()
            };
            modelo.addRow(fila);
        }
    }
    
