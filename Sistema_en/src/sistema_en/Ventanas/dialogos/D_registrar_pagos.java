    public void cargar_datos_tabla(int indice) {
        this.t_monto.setText(String.valueOf(this.Tabla_pagos.getValueAt(indice, 1)));
        this.t_concepto.setText(String.valueOf(this.Tabla_pagos.getValueAt(indice, 2)));

        Object valorFecha = this.Tabla_pagos.getValueAt(indice, 3);

        if (valorFecha != null && !valorFecha.toString().trim().isEmpty() && !valorFecha.toString().equals("null")) {
            String fechaTexto = valorFecha.toString();

            try {
                // OPCIÓN A: Si tu tabla guarda las fechas con guiones (ej: 1995-12-25)
                java.time.LocalDate fecha = java.time.LocalDate.parse(fechaTexto);
                this.d_fecha_pago.setDate(fecha);

                // OPCIÓN B: Si tu tabla muestra las fechas con barras (ej: 25/12/1995), 
                // descomenta las siguientes 3 líneas y borra las de la OPCIÓN A:
                // java.time.format.DateTimeFormatter formateador = java.time.format.DateTimeFormatter.ofPattern("dd/MM/yyyy");
                // java.time.LocalDate fecha = java.time.LocalDate.parse(fechaTexto, formateador);
                // this.f_f_nac.setDate(fecha);
            } catch (Exception e) {
                System.out.println("Error al transformar la fecha de la tabla : " + e.getMessage());
                this.d_fecha_pago.setDate(null); // Si falla el parseo, lo dejamos limpio
            }
        } else {
            this.d_fecha_pago.setDate(null); // Si la tabla no tenía fecha, limpiamos el DatePicker
        }

    }

    public void llenar_tabla() {
        
        
        DefaultTableModel modelo = (DefaultTableModel) this.Tabla_pagos.getModel();//crea una variable de tipo modelo de tabla 
        modelo.setRowCount(0);
        
        CotizacionDAO DAO = new CotizacionDAO();
        String total = DAO.obtenerTotal(id_trabajo);
        
        PagoDAO dao = new PagoDAO();
        List<Pago> listaPagos = dao.obtenerPagos(id_trabajo);
        
        for (Pago p : listaPagos) {
            Object[] fila = new Object[4]; 
            fila[0] = p.getId_pago();
            fila[1] = p.getMonto();
            fila[2] = p.getConcepto();
            fila[3] = p.getFecha_pago();
            modelo.addRow(fila);
        }
        
        this.Tabla_pagos.setModel(modelo);
        
        float total_abonado = dao.sumarPagosPorTrabajo(id_trabajo);
        t_abonado.setText(formatearMoneda(total_abonado));
        
        float total_presupuestado = parsearMonto(total);
        float diferencia = total_presupuestado - total_abonado;
        if (diferencia < 0) {
            diferencia = 0;
        }
        
        t_saldo_pendiente.setText(formatearMoneda(diferencia));
        
    }

