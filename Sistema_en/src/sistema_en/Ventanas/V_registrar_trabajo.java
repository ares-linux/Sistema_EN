    public void llenar_tabla(){
        String [] info = new String [9];
    
        // 1. Emparejar los índices con el orden real de las columnas de la tabla
        info[0] = this.t_id.getText();                               // Id_trabajo
        info[1] = this.C_estado.getSelectedItem().toString();        // Estado
        info[2] = this.t_nombre_cli.getText();                       // nombre_cli
        info[3] = this.t_telefono.getText();                         // telefono
        info[4] = this.t_correo.getText();                           // correo
        info[5] = this.t_direccion.getText();                        // direccion
        info[6] = this.t_descripcion.getText();                      // descripcion

        // Manejo y formato de la Hora
        java.util.Date horaSpinner = (java.util.Date) S_hora.getValue();
        java.text.SimpleDateFormat formatoHora = new java.text.SimpleDateFormat("HH:mm");
        info[7] = formatoHora.format(horaSpinner);                   // hora

         // Manejo y formato de la Fecha
        if (this.D_fecha.getDate() != null) {
            java.text.SimpleDateFormat formatoFecha = new java.text.SimpleDateFormat("dd/MM/yyyy");
            info[8] = formatoFecha.format(this.D_fecha.getDate());   // fecha
        } else {
            info[8] = "";
        }

        // 2. Insertar la fila estructurada en el componente de la ventana principal
        DefaultTableModel modelo = (DefaultTableModel) this.trabajos.Tabla_trabajos.getModel();
        modelo.addRow(info);
        this.trabajos.Tabla_trabajos.setModel(modelo);

        // Forzar actualización visual en la pantalla de destino
        this.trabajos.Tabla_trabajos.revalidate();
        this.trabajos.Tabla_trabajos.repaint();
        }
    
