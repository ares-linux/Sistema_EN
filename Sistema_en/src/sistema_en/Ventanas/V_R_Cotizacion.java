    public void editar_tabla(){
        int selMaterial = this.Tabla_materiales.getSelectedRow();
        int selConcepto = this.Tabla_conceptos.getSelectedRow();
        
        if (selMaterial >= 0) {
            fila = selMaterial;
            editar_tabla_m();
        } else if (selConcepto >= 0) {
            fila = selConcepto;
            editar_tabla_c();
        }
        calcular_total();
    }
    
