    private void obtener_configuraciones(){
        
        ConfiguracionesDAO dao = new ConfiguracionesDAO();
        List<String[]> configs = dao.obtenerConfiguraciones();
    
        for (String[] conf : configs) {

        String clave = conf[1];
        String valor = conf[2];

        switch (clave) {
            case "carpeta_ce":
                ruta_pdf = valor + "/Cotizaciones/";
            break;
            
            case "automaticamente_ce":
                abrir_automaticamente = Boolean.parseBoolean(valor);
            break;
            
            case "cotizaciones":
                cotizaciones1 = valor;
            break;
            
            case "automaticamente_ce_excel":
                abrir_automaticamente_excel = Boolean.parseBoolean(valor);
            break;
        }
        
        }
    }
    
