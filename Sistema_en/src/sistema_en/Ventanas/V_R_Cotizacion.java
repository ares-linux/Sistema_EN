    public void llenar_tabla_m(){
        calcular_total_m();
        Object [] info = new Object[4];
        info[0] = t_nombre_m.getText();
        info[1] = t_precio_uni.getText();
        info[2] = t_cantidad.getText();
        info[3] = total;
        DefaultTableModel modelo=(DefaultTableModel) this.Tabla_materiales.getModel();//crea una variable de tipo modelo de tabla 
        modelo.addRow(info);//agrega una fila al modelo de tabla
        this.Tabla_materiales.setModel(modelo);
    }
    
    public void editar_tabla_m(){
        DefaultTableModel modelo =(DefaultTableModel) this.Tabla_materiales.getModel();
        modelo.setValueAt(this.t_nombre_m.getText(), fila, 0);
        modelo.setValueAt(this.t_precio_uni.getText(), fila, 1);
        modelo.setValueAt(this.t_cantidad.getText(), fila, 2);
        calcular_total_m();
        modelo.setValueAt(total, fila, 3);
    }
    
