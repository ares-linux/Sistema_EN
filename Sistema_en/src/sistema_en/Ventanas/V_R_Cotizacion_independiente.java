    /**
     * Abre la ventana de cotizaciones listas para una nueva. La usan el menu (que
     * antes creaba y guardaba su propia instancia) y formWindowOpened.
     */
    public static void abrirNueva() {
        V_R_Cotizacion_independiente ventana = obtenerInstancia();
        if (!confirmarReemplazo(ventana)) {
            llevarAlFrente(ventana);
            return;
        }
        ventana.cotizacion_prueba();
        llevarAlFrente(ventana);
    }

    /**
     * Abre (o reutiliza) la ventana y carga la cotizacion indicada. La usa el
     * historial; el limite de una sola instancia hace imposible acumular varios
     * formularios con uno o dos clics.
     *
     * @param id cotizacion independiente a cargar
     */
    public static void abrirCotizacion(int id) {
        V_R_Cotizacion_independiente ventana = obtenerInstancia();
        if (!confirmarReemplazo(ventana)) {
            llevarAlFrente(ventana);
            return;
        }
        ventana.cotizacion_prueba();
        ventana.abrirCotizacionPorId(id);
        llevarAlFrente(ventana);
    }

    private static V_R_Cotizacion_independiente obtenerInstancia() {
        if (instancia == null || !instancia.isDisplayable()) {
            V_R_Cotizacion_independiente ventana = new V_R_Cotizacion_independiente();
            instancia = ventana;
            ventana.setExtendedState(javax.swing.JFrame.MAXIMIZED_BOTH);
            ventana.cotizacion_prueba();
            ventana.setVisible(true);
            recienReiniciada = true;
        } else {
            recienReiniciada = false;
        }
        return instancia;
    }

    /**
     * Pide confirmacion antes de descartar lo que haya en curso cuando se reutiliza
     * la misma ventana para cargar otra cotizacion o empezar una nueva. No pregunta
     * si la ventana es la que acaba de crearse en este mismo abrir (aun no hay nada
     * del usuario que descartar).
     *
     * @return true si se puede continuar, false si el usuario cancelo
     */
    private static boolean confirmarReemplazo(V_R_Cotizacion_independiente ventana) {
        if (recienReiniciada || (!ventana.nuevo && !ventana.editar)) {
            return true;
        }
        String descripcion = ventana.id_cotizacion_c > 0
                ? "la cotizacion " + ventana.id_cotizacion_c
                : "una cotizacion nueva";
        int opcion = JOptionPane.showConfirmDialog(ventana,
                "Ya hay " + descripcion + " en edicion.\n"
                + "Si continuas se descartaran los cambios sin guardar.",
                "Reemplazar cotizacion", JOptionPane.YES_NO_OPTION,
                JOptionPane.WARNING_MESSAGE);
        return opcion == JOptionPane.YES_OPTION;
    }

    private static void llevarAlFrente(V_R_Cotizacion_independiente ventana) {
        ventana.setExtendedState(javax.swing.JFrame.MAXIMIZED_BOTH);
        ventana.toFront();
        ventana.requestFocus();
    }

    /**
     * Carga en el formulario una cotizacion independiente existente por su id. La
     * usan el historial y la propia vista despues de crear o convertir.
     *
     * Las cotizaciones de un trabajo viven en V_R_Cotizacion y no deben abrirse
     * aqui: como ambas ventanas comparten la tabla Cotizacion, guardar una de
     * trabajo desde esta pantalla la reescribiria con tipo Prueba y sin trabajo,
     * desvinculandola del trabajo al que pertenece.
     *
     * @param id_cotizacion_i cotizacion a cargar
     * @return true si la cotizacion existe y es independiente
     */
    public boolean abrirCotizacionPorId(int id_cotizacion_i){
        CotizacionDAO dao = new CotizacionDAO();
        Cotizacion c = dao.obtenerCotizacion(id_cotizacion_i);

        if (c == null) {
            JOptionPane.showMessageDialog(this,
                    "No existe la cotizacion " + id_cotizacion_i + ".\n"
                    + "Puede que se haya eliminado o que el id no corresponda.",
                    "Cotizacion no encontrada", JOptionPane.WARNING_MESSAGE);
            return false;
        }

        if (!TIPO_INDEPENDIENTE.equals(c.getTipo())) {
            JOptionPane.showMessageDialog(this,
                    "La cotizacion " + id_cotizacion_i + " pertenece a un trabajo "
                    + "(tipo Normal).\n"
                    + "Por diseño se edita desde la ficha de ese trabajo, no acá.",
                    "Cotizacion no independiente", JOptionPane.WARNING_MESSAGE);
            return false;
        }

        id_trabajo_c = SIN_TRABAJO;
        nuevo = false;
        editar = true;

        if (c.getFecha_creacion() != null) {
            t_fecha_r.setText(c.getFecha_creacion().toString());
        }

        t_id_cotizacion.setText(String.valueOf(c.getId_cotizacion()));
        id_cotizacion_c = c.getId_cotizacion();
        t_subtotal.setText(String.format("%.2f", c.getSubtotal()));
        t_iva.setText(String.format("%.2f", c.getIva()));
        t_total.setText(String.format("%.2f", c.getTotal()));
        c_estado.setSelectedItem(c.getEstado());

        t_nombre_cliente.setText(valorSeguro(c.getNombre_cliente()));
        t_telefono_cliente.setText(valorSeguro(c.getTelefono_cliente()));

        // El nombre que se imprime en PDF y Sheets es el del prospecto, porque
        // una cotizacion independiente nunca tiene cliente registrado.
        n_cliente = valorSeguro(c.getNombre_cliente());

        obtener_detalles(c.getId_cotizacion());

        desbloquear_text();
        desbloquear_tabla();
        b_guardar.setEnabled(true);
        actualizarEstadoBotonConvertir();
        return true;
    }

