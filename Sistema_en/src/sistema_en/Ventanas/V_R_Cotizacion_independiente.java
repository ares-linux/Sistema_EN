    private void b_guardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_b_guardarActionPerformed
        if (nuevo == true){
            try {
                // 1. Validar que existan importes válidos
                if (t_subtotal.getText().trim().isEmpty() || t_iva.getText().trim().isEmpty() || t_total.getText().trim().isEmpty()) {
                    JOptionPane.showMessageDialog(this, "Debe ingresar al menos un concepto o material para calcular los montos.", "Advertencia", JOptionPane.WARNING_MESSAGE);
                    return;
                }

                float subtotal = Float.parseFloat(t_subtotal.getText().replace(",", "."));
                float iva = Float.parseFloat(t_iva.getText().replace(",", "."));
                float total = Float.parseFloat(t_total.getText().replace(",", "."));

                String estado = (c_estado.getSelectedItem() != null) ? c_estado.getSelectedItem().toString() : "Borrador";
                String tipo = TIPO_INDEPENDIENTE;

                // 2. Crear el objeto principal Cotización
                Cotizacion cot = new Cotizacion();
                cot.setSubtotal(subtotal);
                cot.setIva(iva);
                cot.setTotal(total);
                cot.setEstado(estado);
                cot.setTipo(tipo);
                cot.setFecha_creacion(java.time.LocalDate.now());
                cot.setId_trabajo(id_trabajo_c);
                cot.setNombre_cliente(t_nombre_cliente.getText().trim());
                cot.setTelefono_cliente(t_telefono_cliente.getText().trim());

                // 3. Recopilar todos los detalles (Conceptos + Materiales)
                List<Detalles_cotizacion> listaDetalles = new ArrayList<>();

                // Extraer de Tabla_conceptos
                for (int i = 0; i < Tabla_conceptos.getRowCount(); i++) {
                    Detalles_cotizacion det = new Detalles_cotizacion();
                    det.setConcepto(Tabla_conceptos.getValueAt(i, 1).toString());
                    det.setPrecio(Float.parseFloat(Tabla_conceptos.getValueAt(i, 2).toString()));
                    det.setN_material("");
                    det.setCantidad(0);
                    det.setPrecio_uni(0);
                    listaDetalles.add(det);
                }

                // Extraer de Tabla_materiales
                for (int i = 0; i < Tabla_materiales.getRowCount(); i++) {
                    Detalles_cotizacion det = new Detalles_cotizacion();
                    det.setConcepto("");
                    det.setN_material(Tabla_materiales.getValueAt(i, 1).toString());
                    det.setPrecio_uni(Float.parseFloat(Tabla_materiales.getValueAt(i, 2).toString()));
                    det.setCantidad(Float.parseFloat(Tabla_materiales.getValueAt(i, 3).toString()));
                    det.setPrecio(Float.parseFloat(Tabla_materiales.getValueAt(i, 4).toString()));
                    listaDetalles.add(det);
                }

                // 4. Ejecutar la transacción completa
                CotizacionDAO dao = new CotizacionDAO();
                int idCotizacionNueva = dao.insertarCotizacionConDetallesDevolviendoId(cot, listaDetalles);
                boolean exito = idCotizacionNueva != -1;

                if (exito) {
                    // No hay lista donde mostrar la cotización recién creada, así que
                    // el formulario sigue editable y se recarga apuntando al registro
                    // nuevo para que el usuario pueda seguir capturando sobre el.
                    creacion_exitosa();
                    nuevo = false;
                    editar = false;
                    b_guardar.setEnabled(true);
                    cargarCotizacionRecienCreada(idCotizacionNueva);
                } else {
                    JOptionPane.showMessageDialog(this, "Ocurrió un error al intentar guardar la cotización. Ningún dato fue modificado.", "Error", JOptionPane.ERROR_MESSAGE);
                }
            } catch (NumberFormatException e) {
                JOptionPane.showMessageDialog(this, "Por favor verifica que los importes y precios sean valores numéricos válidos.", "Error de formato", JOptionPane.ERROR_MESSAGE);
            } catch (Exception e) {
                System.err.println("Error inesperado al guardar la cotización: " + e.getMessage());
                JOptionPane.showMessageDialog(this, "Error inesperado al guardar la cotización: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
            }
        }

        if (editar == true){
            try {
                // 1. Obtener y validar datos principales
                if (t_subtotal.getText().trim().isEmpty() || t_iva.getText().trim().isEmpty() || t_total.getText().trim().isEmpty()) {
                    JOptionPane.showMessageDialog(this, "Los totales no pueden estar vacíos.", "Error", JOptionPane.WARNING_MESSAGE);
                    return;
                }

                int id_cotizacion = Integer.parseInt(t_id_cotizacion.getText().trim());
                float subtotal = Float.parseFloat(t_subtotal.getText().replace(",", ".").trim());
                float iva = Float.parseFloat(t_iva.getText().replace(",", ".").trim());
                float total = Float.parseFloat(t_total.getText().replace(",", ".").trim());

                String estado = (c_estado.getSelectedItem() != null) ? c_estado.getSelectedItem().toString() : "Borrador";
                String tipo = TIPO_INDEPENDIENTE;
                String fecha_creacion = t_fecha_r.getText().trim();
                int id_trabajo = id_trabajo_c;

                CotizacionDAO DAO = new CotizacionDAO();

                // 2. Recopilar los detalles (Conceptos + Materiales) manteniendo su id si existen
                List<Detalles_cotizacion> listaDetalles = new ArrayList<>();

                for (int i = 0; i < Tabla_conceptos.getRowCount(); i++) {
                    Detalles_cotizacion det = new Detalles_cotizacion();
                    Object valId = Tabla_conceptos.getValueAt(i, 0);
                    String idStr = (valId != null) ? valId.toString().trim() : "";
                    if (!idStr.isEmpty()) {
                        det.setId_detalle(Integer.parseInt(idStr));
                    }
                    det.setConcepto(Tabla_conceptos.getValueAt(i, 1).toString());
                    det.setPrecio(Float.parseFloat(Tabla_conceptos.getValueAt(i, 2).toString()));
                    det.setN_material("");
                    det.setCantidad(0);
                    det.setPrecio_uni(0);
                    listaDetalles.add(det);
                }

                for (int i = 0; i < Tabla_materiales.getRowCount(); i++) {
                    Detalles_cotizacion det = new Detalles_cotizacion();
                    Object valId = Tabla_materiales.getValueAt(i, 0);
                    String idStr = (valId != null) ? valId.toString().trim() : "";
                    if (!idStr.isEmpty()) {
                        det.setId_detalle(Integer.parseInt(idStr));
                    }
                    det.setConcepto("");
                    det.setN_material(Tabla_materiales.getValueAt(i, 1).toString());
                    det.setPrecio_uni(Float.parseFloat(Tabla_materiales.getValueAt(i, 2).toString()));
                    det.setCantidad(Float.parseFloat(Tabla_materiales.getValueAt(i, 3).toString()));
                    det.setPrecio(Float.parseFloat(Tabla_materiales.getValueAt(i, 4).toString()));
                    listaDetalles.add(det);
                }

                // 3. Actualizar cabecera + detalles en una sola transacción
                boolean cotizacionActualizado = DAO.actualizarCotizacionConDetalles(
                    subtotal, iva, total, estado, tipo, fecha_creacion, id_trabajo, id_cotizacion, listaDetalles);

                // Los datos del prospecto viven fuera de esa transacción, así que se
                // avisa si fallan por separado en lugar de perder el resto de la edición.
                // Se guardan siempre: el INSERT ya los escribe sin mirar el tipo, así que
                // filtrar por "Prueba" dejaba la edición inconsistente con la creación.
                boolean prospectoActualizado = true;
                if (cotizacionActualizado) {
                    prospectoActualizado = DAO.actualizarDatosProspecto(id_cotizacion,
                            t_nombre_cliente.getText().trim(), t_telefono_cliente.getText().trim());
                }

                if (cotizacionActualizado) {
                    if (!prospectoActualizado) {
                        JOptionPane.showMessageDialog(this, "Se guardaron los importes, pero no los datos del prospecto.", "Aviso", JOptionPane.WARNING_MESSAGE);
                    }
                    // 4. Restablecer interfaz: sin lista que refrescar, el formulario
                    // se queda editable y cargando la cotización ya guardada.
                    edicion_exitosa();
                    editar = false;
                    nuevo = false;
                    b_guardar.setEnabled(true);
                    b_cancelar.setEnabled(false);
                    cargarCotizacionRecienCreada(id_cotizacion);
                } else {
                    if ("Aprobada".equals(c_estado.getSelectedItem())){
                        JOptionPane.showMessageDialog(this, "No pueden existir mas de una cotizacion aprobada para un mismo trabajo", "Error", JOptionPane.ERROR_MESSAGE);
                    }else{
                        JOptionPane.showMessageDialog(this, "Error al actualizar los datos de la cotización. Ningún dato fue modificado.", "Error", JOptionPane.ERROR_MESSAGE);
                    }
                }
            } catch (NumberFormatException e) {
                JOptionPane.showMessageDialog(this, "Verifica que todos los campos numéricos tengan un formato válido.", "Error de datos", JOptionPane.ERROR_MESSAGE);
            } catch (Exception e) {
                System.err.println("Error inesperado al actualizar la cotización: " + e.getMessage());
                JOptionPane.showMessageDialog(this, "Error inesperado al guardar la cotización: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_b_guardarActionPerformed

    private void b_convertirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_b_convertirActionPerformed
        if (t_id_cotizacion.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Primero guarda la cotizacion independiente.", "Aviso", JOptionPane.WARNING_MESSAGE);
            return;
        }

        int idCotizacion = Integer.parseInt(t_id_cotizacion.getText().trim());
        int respuesta = JOptionPane.showConfirmDialog(this,
                "La cotizacion dejara de ser independiente y quedara vinculada al trabajo nuevo.\n¿Deseas continuar?",
                "Convertir a trabajo", JOptionPane.YES_NO_OPTION, JOptionPane.QUESTION_MESSAGE);

        if (respuesta != JOptionPane.YES_OPTION) {
            return;
        }

        D_convertir_trabajo dialogo = new D_convertir_trabajo(this, true, idCotizacion,
                t_nombre_cliente.getText().trim(),
                t_telefono_cliente.getText().trim(),
                t_total.getText().trim());
        dialogo.setLocationRelativeTo(this);
        dialogo.setVisible(true);

        int idTrabajo = dialogo.getIdTrabajoCreado();
        if (idTrabajo == -1) {
            return;
        }

        // Al convertir, la cotizacion pasa a tipo "Normal" y queda vinculada al
        // trabajo nuevo: deja de ser independiente y sale del alcance de esta
        // ventana, que ya se negaria a abrirla. Se deja el formulario limpio para
        // capturar la siguiente cotizacion independiente.
        JOptionPane.showMessageDialog(this, "La cotizacion quedo vinculada al trabajo " + idTrabajo
                + ".\nAbrela desde la ficha de ese trabajo para editarla.",
                "Trabajo creado", JOptionPane.INFORMATION_MESSAGE);
        cotizacion_prueba();
    }//GEN-LAST:event_b_convertirActionPerformed

