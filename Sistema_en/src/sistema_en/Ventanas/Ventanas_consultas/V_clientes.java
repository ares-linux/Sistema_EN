    private void c_ordenarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_c_ordenarActionPerformed
        String opcion = c_ordenar.getSelectedItem().toString();

        switch (opcion) {

            case "Sin orden":
                llenar_tabla();
                break;
            
            case "Mayor a menor":
                ordenar_mayor_menor();
                break;

            case "Menor a mayor":
                ordenar_menor_mayor();
                break;
                
            case "Nombre A-Z":
                ordenar_nombre_az();
                break;
                
            case "Nombre Z-A":
                ordenar_nombre_za();
                break;
        }
    }//GEN-LAST:event_c_ordenarActionPerformed

