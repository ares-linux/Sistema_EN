    public void llenar_tabla(){
        DefaultTableModel modelo = (DefaultTableModel) this.Tabla_trabajos.getModel();
        modelo.setRowCount(0); 

        TrabajoDAO dao = new TrabajoDAO();
        java.util.List<String[]> listaTrabajos = dao.obtenerTrabajosConClientes();

        for (String[] fila : listaTrabajos) {
            modelo.addRow(fila);
        }
    }
    
    private void Tabla_trabajosMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_Tabla_trabajosMouseClicked
        if (evt.getClickCount() == 2) {
        fila = Tabla_trabajos.rowAtPoint(evt.getPoint());
        if (fila == -1) {
            JOptionPane.showMessageDialog(this, "Seleccione un cliente.");
            return;
        }

        // Cerrar la ficha anterior si ya hay una abierta
        if (ficha != null && ficha.isDisplayable()) {
            ficha.dispose();
        }

        int id_trabajo = Integer.parseInt( Tabla_trabajos.getValueAt(fila, 0).toString());
        int id_cliente = Integer.parseInt( Tabla_trabajos.getValueAt(fila, 1).toString());

        ficha = new D_ficha_trabajo(id_trabajo,id_cliente);
        ficha.setLocationRelativeTo(V_trabajos.this);
        ficha.setVisible(true);
    } 
                
    }//GEN-LAST:event_Tabla_trabajosMouseClicked

    private void b_actualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_b_actualizarActionPerformed
        // Si c_filtro no estaba en "Todos", setSelectedIndex dispara su propio
        // actionPerformed y ya recarga la tabla. Solo rellenamos si no iba a pasar.
        boolean cambiaEstado = c_filtro.getSelectedIndex() != 0;

        D_periodo_inicio.setDate(null);
        D_periodo_fin.setDate(null);
        c_fecha.setSelectedIndex(0);
        c_filtro.setSelectedIndex(0);

        if (!cambiaEstado) {
            llenar_tabla();
        }
    }//GEN-LAST:event_b_actualizarActionPerformed

    public void filtrar_pendiente(){
        DefaultTableModel modelo = (DefaultTableModel) this.Tabla_trabajos.getModel();
        modelo.setRowCount(0); 

        TrabajoDAO dao = new TrabajoDAO();
        java.util.List<String[]> listaTrabajos = dao.obtenerTrabajosConClientesPendiente();

        for (String[] fila : listaTrabajos) {
            modelo.addRow(fila);
        }
        
        if (listaTrabajos.isEmpty()) {
            llenar_tabla();
            JOptionPane.showMessageDialog(this,"No hay trabajos pendientes actualmente.");
        }
    }
    
