    public void filtrar_pendiente(){
        DefaultTableModel modelo = (DefaultTableModel) this.Tabla_trabajos.getModel();
        modelo.setRowCount(0); 

        TrabajoDAO dao = new TrabajoDAO();
        java.util.List<String[]> listaTrabajos = dao.obtenerTrabajosConClientesPendiente();

        for (String[] fila : listaTrabajos) {
            modelo.addRow(fila);
        }
        
        if (listaTrabajos.isEmpty()) {
            llenar_tabla();
            JOptionPane.showMessageDialog(this,"No hay trabajos pendientes actualmente.");
        }
    }
    
    public void filtrar_progreso(){  
        DefaultTableModel modelo = (DefaultTableModel) this.Tabla_trabajos.getModel();
        modelo.setRowCount(0); 

        TrabajoDAO dao = new TrabajoDAO();
        java.util.List<String[]> listaTrabajos = dao.obtenerTrabajosConClientesProgreso();

        for (String[] fila : listaTrabajos) {
            modelo.addRow(fila);
        }
        
        if (listaTrabajos.isEmpty()) {
            llenar_tabla();
            JOptionPane.showMessageDialog(this,"No hay trabajos en progreso actualmente.");
        }
    }
    
    public void filtrar_completados(){
        DefaultTableModel modelo = (DefaultTableModel) this.Tabla_trabajos.getModel();
        modelo.setRowCount(0); 

        TrabajoDAO dao = new TrabajoDAO();
        java.util.List<String[]> listaTrabajos = dao.obtenerTrabajosConClientesCompletado();

        for (String[] fila : listaTrabajos) {
            modelo.addRow(fila);
        }
        
        if (listaTrabajos.isEmpty()){
            llenar_tabla();
            JOptionPane.showMessageDialog(this,"No hay trabajos completados actualmente.");
        }
    }
    
    private void c_filtroActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_c_filtroActionPerformed
        String opcion = c_filtro.getSelectedItem().toString();

        switch (opcion) {

            case "Todos":
                llenar_tabla();
                break;
                
            case "Pendiente":
                filtrar_pendiente();
                break;
                
            case "En progreso":
                filtrar_progreso();
                break;
                
            case "Completado":
                filtrar_completados();
                break;
        }
    }//GEN-LAST:event_c_filtroActionPerformed

