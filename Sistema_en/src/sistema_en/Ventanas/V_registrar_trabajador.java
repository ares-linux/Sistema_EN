    private void b_nuevoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_b_nuevoActionPerformed
        b_cerrar.setEnabled(false);
        desbloquear_botones();
        // Evaluamos el estado del botón usando .equals() en lugar de ==
    if (b_nuevo.getText().equals("Nuevo")) {
        // 1. Cambiamos el texto del botón a Guardar
        b_nuevo.setText("Guardar");
        
        // 2. Limpiamos los residuos que tengan los campos y habilitamos la edición
        limpiar_text();
        desbloquear_text();
        
        // 3. Dejamos el ID vacío ya que la base de datos lo generará automáticamente
        this.t_id.setText("");
        
    } else {
        // Bloque de Guardado (Segundo Clic)
        
        // Validamos que los campos obligatorios no estén vacíos
        if(t_nombre.getText().trim().isEmpty() ||
           t_acta_nac.getText().trim().isEmpty() || 
           t_nss.getText().trim().isEmpty() ||
           t_curp.getText().trim().isEmpty() ||
           t_rfc.getText().trim().isEmpty() ||
           t_foto.getText().trim().isEmpty() ||
           t_ine.getText().trim().isEmpty() ||
           t_comprobante_d.getText().trim().isEmpty()
           ) {
            
            // Opcional: puedes agregar un JOptionPane aquí avisando que faltan campos
            javax.swing.JOptionPane.showMessageDialog(this,"Por favor, llene todos los campos obligatorios.");
            return; 
        }
        
        // Comprobamos si la referencia a la ventana externa existe antes de intentar guardar y refrescar
        if (this.trabajadores != null) {
            // TODO: Guardar en la base de datos aquí: e.g. TrabajadorDAO.insertar(...)
            
            // Refrescamos la tabla consultando la base de datos
            this.trabajadores.cargarTrabajadoresDesdeBD();
        } else {
            System.out.println("Error: La referencia a 'V_trabajadores' es nula. Asegúrate de pasar 'this' en el constructor.");
        }
        
        
        javax.swing.JOptionPane.showMessageDialog(this,"Empleado registrado");
                
        // Restablecemos el estado del formulario para un próximo registro
        bloquear_botones();
        b_cerrar.setEnabled(true);
        b_nuevo.setText("Nuevo");
        b_foto.setEnabled(false);
        bloquear_text();
        
        
    }
    }//GEN-LAST:event_b_nuevoActionPerformed

